import {render,screen,fireEvent,waitFor} from "@testing-library/react";
import {describe,it,expect,vi} from "vitest";
import App from "../App";
import catalog from "./tagging-catalog.json";
import type {TaggingCatalog,Snapshot} from "../types";
import {fakeBridge,track} from "./bridge";
import TaggingSettings from "../views/TaggingSettings";

describe("automatic tagging Settings",()=>{
  it("reports pending cleanup and known retained temporary bytes without hiding unknown sizes",async()=>{
    const bridge=fakeBridge([]);
    bridge.getTaggingStorage=vi.fn(async()=>({original_files:2,original_bytes:1048576,pending_cleanup:2,retained_cleanup_files:3,retained_cleanup_bytes:2097152,retained_cleanup_unknown_sizes:1}));
    render(<TaggingSettings bridge={bridge} config={null} enabled={false} onChange={()=>{}}/>);
    expect(await screen.findByText("1.0 MB · 2 files")).toBeInTheDocument();
    expect(screen.getByText(/Pending cleanup: 2 operations/)).toHaveTextContent("Temporary files retained: 3 · 2.0 MB measured");
    expect(screen.getByText(/Size unavailable for 1 file/)).toBeInTheDocument();
  });
  it("refreshes detected restrictions while mounted without losing selected providers or draft edits",async()=>{
    const bridge=fakeBridge([]);
    let access:NonNullable<TaggingCatalog["access"]>=[];
    bridge.getTaggingCatalog=vi.fn(async()=>({...structuredClone(catalog as TaggingCatalog),access}));
    const config=structuredClone((catalog as TaggingCatalog).defaults);
    const change=vi.fn();
    const page=render(<TaggingSettings bridge={bridge} config={config} enabled onChange={change} catalogRevision={0}/>);
    expect(await screen.findByLabelText("Use Traxsource")).toBeChecked();
    access=[{id:"traxsource",requires_solver:true}];
    page.rerender(<TaggingSettings bridge={bridge} config={config} enabled onChange={change} catalogRevision={1}/>);
    await screen.findByText("Unavailable · configure a solver");
    expect(screen.getByLabelText("Use Traxsource")).toBeChecked();
    fireEvent.click(screen.getByLabelText("Use Traxsource"));
    const unselected=change.mock.calls.at(-1)![0];
    page.rerender(<TaggingSettings bridge={bridge} config={unselected} enabled onChange={change} catalogRevision={1}/>);
    expect(screen.getByLabelText("Use Traxsource")).toBeDisabled();
  });
  it("disables a detected blocked source until a solver is configured and persists its timeout",async()=>{
    const bridge=fakeBridge([]);
    bridge.getTaggingCatalog=vi.fn(async()=>({...structuredClone(catalog as TaggingCatalog),access:[{id:"traxsource",requires_solver:true}]}));
    render(<App bridge={bridge}/>);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    fireEvent.click(await screen.findByRole("button",{name:"Automatic tagging"}));
    expect(await screen.findByLabelText("Use Traxsource")).toBeDisabled();
    fireEvent.change(screen.getByLabelText("Solver API URL"),{target:{value:"http://localhost:8191/v1"}});
    expect(screen.getByLabelText("Use Traxsource")).toBeEnabled();
    fireEvent.click(screen.getByLabelText("Use Traxsource"));
    fireEvent.change(screen.getByLabelText("Solver timeout"),{target:{value:"180"}});
    fireEvent.click(screen.getByRole("button",{name:/Save settings/}));
    await waitFor(()=>expect(bridge.saveSettings).toHaveBeenCalled());
    const saved=vi.mocked(bridge.saveSettings).mock.calls.at(-1)![0];
    expect(saved.tagging?.solver).toEqual({endpoint:"http://localhost:8191/v1",timeout_seconds:180});
    expect(saved.tagging?.options.platforms).toContain("traxsource");
  });
  it("persists provider order, field policies and catalog options across remount",async()=>{
    const bridge=fakeBridge([]);
    bridge.getTaggingStorage=vi.fn(async()=>({original_files:2,original_bytes:1048576,pending_cleanup:0}));
    const first=render(<App bridge={bridge}/>);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    fireEvent.click(await screen.findByRole("button",{name:"Automatic tagging"}));
    fireEvent.click(await screen.findByLabelText("Automatic tagging"));
    await screen.findByText("1.0 MB · 2 files");
    fireEvent.click(screen.getByRole("button",{name:"Move Traxsource earlier"}));
    fireEvent.click(screen.getByLabelText("Write Title"));
    fireEvent.click(screen.getByLabelText("Overwrite all selected fields"));
    fireEvent.click(screen.getByLabelText("Overwrite Title"));
    fireEvent.change(screen.getByLabelText("Max pages"),{target:{value:"4"}});
    fireEvent.change(screen.getByLabelText("No catalog match"),{target:{value:"attention"}});
    fireEvent.change(screen.getByLabelText("Key and BPM written to files"),{target:{value:"catalog"}});
    fireEvent.click(screen.getByRole("button",{name:/Save settings/}));
    await waitFor(()=>expect(bridge.saveSettings).toHaveBeenCalled());
    const saved=vi.mocked(bridge.saveSettings).mock.calls.at(-1)![0];
    expect(saved.autotag_enabled).toBe(true);
    expect(saved.tagging?.options.platforms).toEqual(["traxsource","beatport"]);
    expect(saved.tagging?.options.tags).toContain("title");
    expect(saved.tagging?.options.overwriteTags).toContain("title");
    expect(saved.tagging?.options.overwrite).toBe(false);
    expect(saved.tagging?.options.custom.beatport.max_pages).toBe(4);
    expect(saved.tagging?.no_match).toBe("attention");
    expect(saved.tagging?.analysis_tag_source).toBe("catalog");
    first.unmount();render(<App bridge={bridge}/>);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    fireEvent.click(await screen.findByRole("button",{name:"Automatic tagging"}));
    expect(await screen.findByLabelText("Automatic tagging")).toBeChecked();
    expect(screen.getByLabelText("Max pages")).toHaveValue(4);
    expect(screen.getByLabelText("No catalog match")).toHaveValue("attention");
    expect(screen.queryByLabelText(/Spotify|Shazam|Post command/)).not.toBeInTheDocument();
  },15_000);
  it("retains unavailable source options and required fields when saving unrelated settings",async()=>{
    const bridge=fakeBridge([]),available=structuredClone(catalog) as TaggingCatalog;
    available.access=[{id:"traxsource",requires_solver:true}];
    bridge.getTaggingCatalog=vi.fn(async()=>available);
    const state=await bridge.getState();
    await bridge.saveSettings({...state.settings.settings,tagging:{...available.defaults,required_tags:["title"],options:{...available.defaults.options,platforms:["traxsource","beatport"],custom:{...available.defaults.options.custom,traxsource:{private_option:"preserve"}}}}});
    vi.mocked(bridge.saveSettings).mockClear();
    render(<App bridge={bridge}/>);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    fireEvent.click(await screen.findByRole("button",{name:"Automatic tagging"}));
    expect(await screen.findByLabelText("Use Traxsource")).toBeChecked();
    expect(screen.getByLabelText("Use Traxsource")).toBeEnabled();
    expect(screen.getByText("Unavailable · configure a solver")).toBeInTheDocument();
    fireEvent.change(screen.getByLabelText("Max pages"),{target:{value:"3"}});
    fireEvent.click(screen.getByRole("button",{name:/Save settings/}));
    await waitFor(()=>expect(bridge.saveSettings).toHaveBeenCalled());
    const saved=vi.mocked(bridge.saveSettings).mock.calls.at(-1)![0];
    expect(saved.tagging?.options.platforms).toEqual(["traxsource","beatport"]);
    expect(saved.tagging?.options.custom.traxsource).toEqual({private_option:"preserve"});
    expect(saved.tagging?.required_tags).toEqual(["title"]);
  });
  it("ignores a catalog response after leaving Settings and can retry a load failure",async()=>{
    const bridge=fakeBridge([]);
    let release!:(value:TaggingCatalog)=>void;
    bridge.getTaggingCatalog=vi.fn().mockImplementationOnce(()=>new Promise(resolve=>{release=resolve;})).mockRejectedValueOnce(new Error("Options unavailable")).mockResolvedValue(catalog);
    render(<App bridge={bridge}/>);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    fireEvent.click(await screen.findByRole("button",{name:"Automatic tagging"}));
    await screen.findByText("Loading tagging settings…");
    fireEvent.click(screen.getByRole("button",{name:"Library"}));
    release(catalog as TaggingCatalog);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    fireEvent.click(await screen.findByRole("button",{name:"Automatic tagging"}));
    await screen.findByText("Options unavailable");
    fireEvent.click(screen.getByRole("button",{name:"Retry loading tagging settings"}));
    await screen.findByLabelText("Automatic tagging");
  });
  it("retains edits when a save fails and prevents edits during publication",async()=>{
    const bridge=fakeBridge([]);
    let reject!:(error:Error)=>void;
    bridge.saveSettings=vi.fn(()=>new Promise<Snapshot>((_,fail)=>{reject=fail;}));
    render(<App bridge={bridge}/>);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    fireEvent.click(await screen.findByRole("button",{name:"Automatic tagging"}));
    fireEvent.click(await screen.findByLabelText("Automatic tagging"));
    fireEvent.change(screen.getByLabelText("Max pages"),{target:{value:"3"}});
    fireEvent.click(screen.getByRole("button",{name:/Save settings/}));
    expect(screen.getByLabelText("Max pages")).toBeDisabled();
    reject(new Error("Settings could not be saved"));
    await screen.findByText("Settings could not be saved");
    expect(screen.getByLabelText("Max pages")).toBeEnabled();
    expect(screen.getByLabelText("Max pages")).toHaveValue(3);
  });
  it("makes external artwork an explicit alternative to embedded artwork",async()=>{
    const bridge=fakeBridge([]);
    render(<App bridge={bridge}/>);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    fireEvent.click(await screen.findByRole("button",{name:"Automatic tagging"}));
    await screen.findByLabelText("Automatic tagging");
    fireEvent.click(screen.getByText("Artwork",{selector:"summary"}));
    fireEvent.change(screen.getByLabelText("Artwork destination"),{target:{value:"external"}});
    expect(screen.getByText(/Existing embedded covers are retained/)).toBeInTheDocument();
    fireEvent.click(screen.getByRole("button",{name:/Save settings/}));
    await waitFor(()=>expect(bridge.saveSettings).toHaveBeenCalled());
    expect(vi.mocked(bridge.saveSettings).mock.calls[0][0].tagging?.options.albumArtFile).toBe(true);
  });
  it("shows required catalog and writing stages in Incoming",async()=>{
    const bridge=fakeBridge([{...track("a"),state:"incoming"}]);
    bridge.jobs=[{id:"job",track_id:"a",title:"Track a",state:"running",stage:"matching",error:null,attempts:1}];
    render(<App bridge={bridge}/>);
    fireEvent.click(screen.getByRole("button",{name:/Incoming/}));
    await screen.findByText("Matching catalog");
    bridge.jobs[0].stage="writing_tags";
    bridge.changed({state:"running",stage:"writing_tags",track_id:"a",job_id:"job",sequence:2});
    await screen.findByText("Writing tags");
  });
});
