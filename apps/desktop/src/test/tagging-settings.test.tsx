import {render,screen,fireEvent,waitFor} from "@testing-library/react";
import {describe,it,expect,vi} from "vitest";
import App from "../App";
import catalog from "./tagging-catalog.json";
import type {TaggingCatalog,Snapshot} from "../types";
import {fakeBridge,track} from "./bridge";

describe("automatic tagging Settings",()=>{
  it("persists provider order, field policies and catalog options across remount",async()=>{
    const bridge=fakeBridge([]);
    const first=render(<App bridge={bridge}/>);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    fireEvent.click(await screen.findByLabelText("Automatic tagging"));
    fireEvent.click(screen.getByRole("button",{name:"Move Traxsource earlier"}));
    fireEvent.click(screen.getByLabelText("Write Title"));
    fireEvent.click(screen.getByLabelText("Overwrite all selected fields"));
    fireEvent.click(screen.getByLabelText("Overwrite Title"));
    fireEvent.change(screen.getByLabelText("Max pages"),{target:{value:"4"}});
    fireEvent.change(screen.getByLabelText("No catalog match"),{target:{value:"attention"}});
    fireEvent.change(screen.getByLabelText("Key and BPM written to files"),{target:{value:"catalog"}});
    fireEvent.click(screen.getByRole("button",{name:/Save settings/}));
    await waitFor(()=>expect(bridge.saveSettings).toHaveBeenCalled());
    const saved=vi.mocked(bridge.saveSettings).mock.calls.at(-1)![0];
    expect(saved.autotag_enabled).toBe(true);
    expect(saved.tagging?.options.platforms).toEqual(["traxsource","beatport"]);
    expect(saved.tagging?.options.tags).toContain("title");
    expect(saved.tagging?.options.overwriteTags).toContain("title");
    expect(saved.tagging?.options.overwrite).toBe(false);
    expect(saved.tagging?.options.custom.beatport.max_pages).toBe(4);
    expect(saved.tagging?.no_match).toBe("attention");
    expect(saved.tagging?.analysis_tag_source).toBe("catalog");
    first.unmount();render(<App bridge={bridge}/>);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    expect(await screen.findByLabelText("Automatic tagging")).toBeChecked();
    expect(screen.getByLabelText("Max pages")).toHaveValue(4);
    expect(screen.getByLabelText("No catalog match")).toHaveValue("attention");
    expect(screen.queryByLabelText(/Spotify|Shazam|Post command/)).not.toBeInTheDocument();
  });
  it("ignores a catalog response after leaving Settings and can retry a load failure",async()=>{
    const bridge=fakeBridge([]);
    let release!:(value:TaggingCatalog)=>void;
    bridge.getTaggingCatalog=vi.fn().mockImplementationOnce(()=>new Promise(resolve=>{release=resolve;})).mockRejectedValueOnce(new Error("Options unavailable")).mockResolvedValue(catalog);
    render(<App bridge={bridge}/>);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    await screen.findByText("Loading tagging settings…");
    fireEvent.click(screen.getByRole("button",{name:"Library"}));
    release(catalog as TaggingCatalog);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    await screen.findByText("Options unavailable");
    fireEvent.click(screen.getByRole("button",{name:"Retry loading tagging settings"}));
    await screen.findByLabelText("Automatic tagging");
  });
  it("retains edits when a save fails and prevents edits during publication",async()=>{
    const bridge=fakeBridge([]);
    let reject!:(error:Error)=>void;
    bridge.saveSettings=vi.fn(()=>new Promise<Snapshot>((_,fail)=>{reject=fail;}));
    render(<App bridge={bridge}/>);
    await screen.findByText("Your library starts here");
    fireEvent.click(screen.getByRole("button",{name:"Settings"}));
    fireEvent.click(await screen.findByLabelText("Automatic tagging"));
    fireEvent.change(screen.getByLabelText("Max pages"),{target:{value:"3"}});
    fireEvent.click(screen.getByRole("button",{name:/Save settings/}));
    expect(screen.getByLabelText("Max pages")).toBeDisabled();
    reject(new Error("Settings could not be saved"));
    await screen.findByText("Settings could not be saved");
    expect(screen.getByLabelText("Max pages")).toBeEnabled();
    expect(screen.getByLabelText("Max pages")).toHaveValue(3);
  });
  it("shows required catalog and writing stages in Incoming",async()=>{
    const bridge=fakeBridge([{...track("a"),state:"incoming"}]);
    bridge.jobs=[{id:"job",track_id:"a",title:"Track a",state:"running",stage:"matching",error:null,attempts:1}];
    render(<App bridge={bridge}/>);
    fireEvent.click(screen.getByRole("button",{name:/Incoming/}));
    await screen.findByText("Matching catalog");
    bridge.jobs[0].stage="writing_tags";
    bridge.changed({state:"running",stage:"writing_tags",track_id:"a",job_id:"job",sequence:2});
    await screen.findByText("Writing tags");
  });
});
